import { test, expect, scenario, api, login, event } from './support'

test('loading lento tem shimmer; erro HTTP mostra feedback e tentativa recupera', async ({ page }) => {
  await scenario(page, 'slow-network')
  await page.goto('/nfts/nft-1')
  await expect(page.locator('.detail-loading .detail-art.skeleton-shimmer')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042', exact: true })).toBeVisible()
  await page.goto('/cart')
  await expect(page.getByRole('status').filter({ hasText: 'Carregando resumo' })).toBeVisible()
  await expect(page.locator('.cart-row')).toHaveCount(3)
  await scenario(page, 'network-error')
  await page.goto('/nfts/nft-1')
  await expect(page.getByRole('heading', { name: 'Não foi possível carregar o NFT' })).toBeVisible()
  await scenario(page, 'default')
  await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042', exact: true })).toBeVisible()
})

test('diálogo autenticação funciona por teclado, valida confirmação e trata conflito', async ({ page }) => {
  await page.goto('/cadastro')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect.poll(() => dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  await page.getByLabel('Nome completo').fill('Teste teclado')
  await page.getByLabel('E-mail', { exact: true }).fill('alex@kurio.art')
  await page.getByLabel('Senha', { exact: true }).fill('nova1234')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('diferente')
  await page.locator('.auth-form button[type=submit]').press('Enter')
  await expect(page.getByRole('alert')).toContainText('confirmação')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('nova1234')
  await page.locator('.auth-form button[type=submit]').press('Enter')
  await expect(page.getByRole('alert')).toContainText('já está cadastrado')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
})

test('respostas fora de ordem não substituem o filtro atual e edição indisponível fica bloqueada', async ({ page }, info) => {
  await scenario(page, 'variable-latency')
  const input = page.getByRole('textbox', { name: info.project.name.includes('Mobile') ? 'Buscar coleções' : 'Buscar NFTs', exact: true })
  await input.fill('Emerald')
  await input.press('Enter')
  await expect(page).toHaveURL(/search=Emerald/)
  await input.fill('Violet')
  await input.press('Enter')
  await expect(page).toHaveURL(/search=Violet/)
  await api(page, 'GET', '/nfts?search=Emerald')
  await expect(page.locator('.nft-card')).toHaveCount(1)
  await expect(page.locator('.nft-card')).toContainText('Violet')
  await page.goto('/nfts/nft-1')
  await expect(page.getByRole('button', { name: '1/1', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '1/10', exact: true }).click()
  const plus = page.getByRole('button', { name: 'Aumentar quantidade', exact: true })
  for (let i = 0; i < 3; i++) await plus.click()
  await expect(plus).toBeDisabled()
  await expect(page.locator('.detail-quantity')).toContainText('4')
})

test('perfil associa nomes e erros aos campos e mantém atualização privada após troca de conta', async ({ page }) => {
  await login(page)
  await page.goto('/profile')
  await expect(page.getByRole('textbox', { name: 'Nome de exibição', exact: true })).toBeVisible()
  await page.getByLabel('Nova senha', { exact: true }).fill('curta')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('Nova senha', { exact: true })).toHaveAttribute('aria-describedby', 'profile-error')
})

test('falha temporária ao recuperar sessão oferece retry e preserva autenticação', async ({ page }) => {
  await login(page)
  await scenario(page, 'network-error')
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: 'Não foi possível recuperar sua sessão' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await scenario(page, 'default')
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Alex Vance')
})

test('estoque esgotado por Socket.IO atualiza carrinho e bloqueia o pagamento', async ({ page }) => {
  await login(page)
  await page.goto('/cart')
  await expect(page.locator('.cart-row').first()).toContainText('Emerald Ape')
  await event(page, { type: 'nft.updated', id: 'nft-1', availableQuantity: 0 })
  await expect(page.getByRole('status').filter({ hasText: 'tempo real' })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('apenas 0 unidades')
  await page.goto('/checkout')
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
})

test('rota inexistente exibe página 404 e permite retornar ao início', async ({ page }) => {
  await page.goto('/rota-inexistente-404')
  await expect(page.getByRole('heading', { name: 'Página não encontrada' })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao início' }).click()
  await expect(page).toHaveURL(/\/(\?.*)?$/)
  await expect(page.locator('.nft-card').first()).toBeVisible()
})

