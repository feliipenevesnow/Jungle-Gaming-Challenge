import { test, expect, type Page } from '@playwright/test'

async function signIn(page: Page, email = 'alex@kurio.art', password = 'kurio123') {
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.locator('.auth-form button[type=submit]').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

test.beforeEach(async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.goto('/')
  await expect(page.locator('.nft-card').first()).toBeVisible()
  await page.evaluate(() => fetch('/api/reset', { method: 'POST' }))
})

test('cupom persiste do visitante ao pagamento e recibo; clique repetido não duplica compra', async ({ page }) => {
  await page.goto('/')
  await page.locator('.nft-card').filter({ hasText: 'Emerald Ape #042' }).locator('.nft-art').click()
  await expect(page).toHaveURL(/\/nfts\/nft-1$/)
  await page.getByRole('button', { name: 'Adicionar ao Carrinho', exact: true }).click()
  await page.getByRole('textbox', { name: 'Código promocional', exact: true }).fill('KURIO10')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'KURIO10' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('status').filter({ hasText: 'KURIO10' })).toBeVisible()
  await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
  await signIn(page)
  await expect(page).toHaveURL(/\/checkout$/)
  const button = page.getByRole('button', { name: 'Confirmar compra' })
  await expect(button).toBeEnabled()
  await page.getByRole('button', { name: 'Tem um código promocional? Aplique aqui' }).click()
  await expect(page.getByRole('dialog')).toContainText('KURIO10')
  await page.getByRole('button', { name: 'Remover cupom' }).click()
  await page.getByRole('textbox', { name: 'Código promocional', exact: true }).fill('NAOEXISTE')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('inválido ou expirado')
  await page.getByRole('textbox', { name: 'Código promocional', exact: true }).fill('EXPIRED50')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('inválido ou expirado')
  await page.getByRole('textbox', { name: 'Código promocional', exact: true }).fill('WELCOME20')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('WELCOME20')
  await page.getByRole('dialog').getByRole('button', { name: 'Fechar', exact: true }).click()
  await expect(button).toBeEnabled()
  const created = page.waitForResponse(response => response.url().endsWith('/api/orders') && response.request().method() === 'POST')
  await button.evaluate(element => { (element as HTMLButtonElement).click(); (element as HTMLButtonElement).click() })
  const order = await (await created).json()
  expect(order.status).toBe('PENDING')
  expect(order.couponCode).toBe('WELCOME20')
  expect(order.discountEth).not.toBe('0.00')
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  await expect(page.locator('.order-receipt')).toContainText(`${order.totalEth} ETH`)
  await page.reload()
  await expect(page.locator('.order-receipt')).toContainText(`${order.totalEth} ETH`)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('kurio_mock_database_v2')!))
  expect(saved.orders).toHaveLength(1)
  expect(saved.cartByUser['user-alex']).toHaveLength(0)
})

test('carrinho antigo acima do estoque explica bloqueio e permite corrigir', async ({ page }) => {
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('kurio_mock_database_v2')!)
    state.cartByUser['user-alex'][1].quantity = 12
    localStorage.setItem('kurio_mock_database_v2', JSON.stringify(state))
  })
  await page.goto('/login')
  await signIn(page)
  await page.goto('/checkout')
  await expect(page.getByRole('alert')).toContainText('apenas 10 unidades')
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
  await page.getByRole('link', { name: 'Ajustar carrinho' }).click()
  await page.getByRole('button', { name: 'Ajustar quantidades ao estoque' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
})

test('pagamento recusado preserva carrinho e não mostra recibo de sucesso', async ({ page }) => {
  await page.goto('/login')
  await signIn(page)
  await page.evaluate(() => localStorage.setItem('kurio_msw_scenario', 'payment-rejected'))
  await page.goto('/checkout')
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Pagamento recusado' })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao carrinho' }).click()
  await expect(page.locator('.cart-row')).toHaveCount(3)
})
